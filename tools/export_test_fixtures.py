"""Adapt existing fixtures, using cleanroom stereo/gain only for kernel isolation.
MDCT expected outputs and QMF expected outputs remain frozen spec checkpoints.
"""
import json,sys,wave
from pathlib import Path
import numpy as np
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from cleanroom.tables import decode
from cleanroom.lp4_stereo import Stereo,apply_gain
stages=json.loads((ROOT/'spec/vectors/stages.json').read_text())['lp4']
with wave.open(str(ROOT/'spec/vectors/transients.wav')) as w: pcm=np.frombuffer(w.readframes(3072),'<i2').tolist()
def literal(a):
 if isinstance(a,list):return '['+','.join(literal(x) for x in a)+']'
 return str(a)
qmf=[];spectra=[];inputs=[];levels=[]
stereo=Stereo();previous=[np.zeros((256,4),np.float32) for _ in range(2)]
for s in stages:
 raw=[decode(v) for v in s['qmf_before_stereo']]
 qmf.append([v.view(np.uint32).reshape(-1).tolist() for v in raw])
 spectra.append([decode(v).view(np.uint32).reshape(-1).tolist() for v in s['spectrum']])
 modified=[];first=[]
 for c in range(2):
  gains=s['gain'][c*4:c*4+4]
  modified.append(np.stack([apply_gain(previous[c][:,b],gains[b]) for b in range(4)],axis=1).view(np.uint32).reshape(-1).tolist())
  first.append([g[0][0] if g else 4 for g in gains])
 inputs.append(modified);levels.append(first);previous=stereo.process(*raw)
lines=['// Generated by tools/export_test_fixtures.py; expected results from frozen spec vectors.']
for name,typ,v in [('PCM','[i16;6144]',pcm),('QMF','[[[u32;1024];2];3]',qmf),('SPECTRUM','[[[u32;1024];2];3]',spectra),('MDCT_INPUT','[[[u32;1024];2];3]',inputs),('FIRST_LEVELS','[[[usize;4];2];3]',levels)]:
 lines.append(f'pub const {name}: {typ} = {literal(v)};')
(ROOT/'tests/data/lp4_kernel_fixtures.rs').write_text('\n'.join(lines)+'\n')

with (ROOT/'tests/data/lp4_kernel_fixtures.rs').open('a') as f:
 f.write('pub const BUDGETS:[i32;3]='+literal([s['budgets'][0] for s in stages])+';\n')
 f.write('pub const SENT:[[i32;4];3]='+literal([s['sent_matrix'] for s in stages])+';\n')
 f.write('pub const WEIGHT:[usize;3]='+literal([s['sent_weight'] for s in stages])+';\n')
 groups=[]
 for s in stages:
  groups.append('['+','.join('&['+','.join(f'({p[0]},{p[1]})' for p in g)+']' for g in s['gain'])+']')
 f.write('pub const GAINS:[[&[(i32,usize)];8];3]=['+','.join(groups)+'];\n')
